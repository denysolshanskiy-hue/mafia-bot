-- CHRONOS foundation: isolated season calendar metadata.
-- This migration does not alter public.users, public.events, or public.registrations.
-- Run manually in Neon SQL Editor only after reviewing the PR.

BEGIN;

CREATE SCHEMA IF NOT EXISTS chronos;

CREATE TABLE IF NOT EXISTS chronos.seasons (
    season_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_code TEXT NOT NULL UNIQUE,
    title TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft', 'active', 'paused', 'completed')),

    start_date DATE,
    end_date DATE,
    target_sync_units INTEGER NOT NULL DEFAULT 690
        CHECK (target_sync_units >= 0),

    regular_evenings_target SMALLINT NOT NULL DEFAULT 9
        CHECK (regular_evenings_target > 0),
    regular_games_per_evening SMALLINT NOT NULL DEFAULT 5
        CHECK (regular_games_per_evening > 0),
    intermediate_finals_target SMALLINT NOT NULL DEFAULT 3
        CHECK (intermediate_finals_target >= 0),
    games_per_intermediate_final SMALLINT NOT NULL DEFAULT 8
        CHECK (games_per_intermediate_final > 0),
    players_per_game SMALLINT NOT NULL DEFAULT 10
        CHECK (players_per_game > 0),
    main_final_games SMALLINT NOT NULL DEFAULT 10
        CHECK (main_final_games > 0),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chronos_seasons_date_order
        CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);

COMMENT ON TABLE chronos.seasons IS
    'CHRONOS season configuration. Kept separate from the existing Mafia bot tables.';
COMMENT ON COLUMN chronos.seasons.target_sync_units IS
    'Season sync target; currently planned as 690 game participations. Main Final games are tracked separately.';
COMMENT ON COLUMN chronos.seasons.players_per_game IS
    'Players per individual Mafia game, not a limit on event registrations or the evening roster.';

CREATE TABLE IF NOT EXISTS chronos.event_slots (
    slot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_id BIGINT NOT NULL
        REFERENCES chronos.seasons(season_id) ON DELETE CASCADE,

    slot_code TEXT NOT NULL,
    sequence_no SMALLINT NOT NULL CHECK (sequence_no > 0),
    slot_type TEXT NOT NULL
        CHECK (slot_type IN ('regular', 'intermediate_final', 'main_final')),
    title TEXT NOT NULL,
    planned_date DATE,

    -- Optional link to the original event created by the existing Telegram bot.
    -- The application must only link events whose public.events.event_type = 'chronos'.
    bot_event_id INTEGER
        REFERENCES public.events(event_id) ON DELETE SET NULL,

    -- This is the planning-slot state only. The live event state remains owned by public.events.
    status TEXT NOT NULL DEFAULT 'planned'
        CHECK (status IN ('planned', 'cancelled')),
    notes TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chronos_event_slots_code_unique
        UNIQUE (season_id, slot_code),
    CONSTRAINT chronos_event_slots_sequence_unique
        UNIQUE (season_id, sequence_no),
    CONSTRAINT chronos_event_slots_bot_event_unique
        UNIQUE (bot_event_id)
);

CREATE INDEX IF NOT EXISTS chronos_event_slots_season_status_idx
    ON chronos.event_slots (season_id, status, sequence_no);

COMMENT ON TABLE chronos.event_slots IS
    'Planned CHRONOS evenings and finals. A slot can be linked to one event already created by the existing bot.';
COMMENT ON COLUMN chronos.event_slots.bot_event_id IS
    'References public.events.event_id. Do not create a second event from the Mini App.';
COMMENT ON COLUMN chronos.event_slots.status IS
    'Planning state only; actual event active/closed state is read from public.events.';

-- Seed a draft season and its 13 planned slots.
-- The first 12 are the season progression evenings (9 regular + 3 intermediate finals).
-- CHRONOS FINAL is a separate, post-100% event and does not add to the 690 sync target.
INSERT INTO chronos.seasons (season_code, title, status, target_sync_units)
VALUES ('CHRONOS', 'ХРАНИТЕЛІ ЧАСУ / CHRONOS', 'draft', 690)
ON CONFLICT (season_code) DO NOTHING;

WITH season AS (
    SELECT season_id FROM chronos.seasons WHERE season_code = 'CHRONOS'
),
planned_slots AS (
    SELECT
        season_id,
        'REG-' || LPAD(n::text, 2, '0') AS slot_code,
        n::smallint AS sequence_no,
        'regular'::text AS slot_type,
        'Регулярний вечір #' || n AS title
    FROM season
    CROSS JOIN GENERATE_SERIES(1, 9) AS n

    UNION ALL

    SELECT
        season_id,
        'IF-' || LPAD(n::text, 2, '0'),
        (9 + n)::smallint,
        'intermediate_final'::text,
        'Проміжний фінал #' || n
    FROM season
    CROSS JOIN GENERATE_SERIES(1, 3) AS n

    UNION ALL

    SELECT
        season_id,
        'MAIN-FINAL',
        13::smallint,
        'main_final'::text,
        'CHRONOS FINAL'
    FROM season
)
INSERT INTO chronos.event_slots (season_id, slot_code, sequence_no, slot_type, title)
SELECT season_id, slot_code, sequence_no, slot_type, title
FROM planned_slots
ON CONFLICT (season_id, slot_code) DO NOTHING;

COMMIT;
