-- CHRONOS v1 economy: closed soft currencies, no-loss forecasts, transparent activity bonus.
-- Apply only after migrations 001, 002 and 003, on staging first.
BEGIN;

-- Prediction Exchange is a free forecast mechanic. Historical "stake" storage is
-- retained for compatibility, but the only allowed new stake is zero.
ALTER TABLE chronos.prediction_bets
    DROP CONSTRAINT IF EXISTS prediction_bets_stake_check;
ALTER TABLE chronos.prediction_bets
    ALTER COLUMN stake SET DEFAULT 0;
ALTER TABLE chronos.prediction_bets
    ADD CONSTRAINT prediction_bets_stake_nonnegative CHECK (stake >= 0);

ALTER TABLE chronos.prediction_candidates
    ADD COLUMN IF NOT EXISTS reward_ex SMALLINT NOT NULL DEFAULT 50
      CHECK (reward_ex BETWEEN 1 AND 500);

CREATE TABLE IF NOT EXISTS chronos.season_bonus_allocations (
    allocation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_id BIGINT NOT NULL REFERENCES chronos.seasons(season_id) ON DELETE CASCADE,
    slot_id BIGINT NOT NULL REFERENCES chronos.event_slots(slot_id) ON DELETE RESTRICT,
    user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE RESTRICT,
    rank_at_lock SMALLINT NOT NULL CHECK (rank_at_lock BETWEEN 1 AND 10),
    games_played INTEGER NOT NULL CHECK (games_played >= 0),
    games_conducted INTEGER NOT NULL CHECK (games_conducted >= 0),
    attended_slots SMALLINT NOT NULL CHECK (attended_slots >= 0),
    eligible_slots SMALLINT NOT NULL CHECK (eligible_slots >= 0),
    verified_app_actions SMALLINT NOT NULL CHECK (verified_app_actions >= 0),
    completed_minigames SMALLINT NOT NULL CHECK (completed_minigames >= 0),
    attendance_points NUMERIC(7,4) NOT NULL CHECK (attendance_points BETWEEN 0 AND 80),
    app_points NUMERIC(7,4) NOT NULL CHECK (app_points BETWEEN 0 AND 15),
    minigame_points NUMERIC(7,4) NOT NULL CHECK (minigame_points BETWEEN 0 AND 5),
    activity_score NUMERIC(7,4) NOT NULL CHECK (activity_score BETWEEN 0 AND 100),
    activity_coefficient NUMERIC(7,6) NOT NULL CHECK (activity_coefficient BETWEEN 0 AND 1),
    pool_amount_uah BIGINT NOT NULL CHECK (pool_amount_uah >= 0),
    allocation_amount_uah BIGINT NOT NULL CHECK (allocation_amount_uah >= 0),
    status TEXT NOT NULL DEFAULT 'draft'
      CHECK (status IN ('draft','approved','paid','void')),
    approved_by BIGINT REFERENCES public.users(user_id),
    approved_at TIMESTAMPTZ,
    paid_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (season_id,user_id),
    UNIQUE (slot_id,rank_at_lock)
);
CREATE INDEX IF NOT EXISTS chronos_bonus_allocations_status_idx
    ON chronos.season_bonus_allocations(season_id,status,rank_at_lock);

