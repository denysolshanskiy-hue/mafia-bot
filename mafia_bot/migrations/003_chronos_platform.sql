-- CHRONOS platform modules: identity, XP/economy, iMafia imports, season stats,
-- mini-games, predictions, notifications, prizes and audit.
-- Does not change the existing bot's public.users/events/registrations structure.
BEGIN;

ALTER TABLE chronos.seasons
    ADD COLUMN IF NOT EXISTS platform_settings JSONB NOT NULL DEFAULT
    '{
      "activity_score": {
        "status": "draft",
        "weights": {"attendance": 80, "app": 15, "minigame": 5}
      },
      "predictions": {
        "status": "draft",
        "min_stake": 10,
        "max_stake": 200,
        "max_per_evening": 500,
        "max_bets_per_evening": 3,
        "house_margin": 0.05
      }
    }'::jsonb;

CREATE TABLE IF NOT EXISTS chronos.profiles (
    user_id BIGINT PRIMARY KEY REFERENCES public.users(user_id) ON DELETE CASCADE,
    avatar_base TEXT NOT NULL DEFAULT 'european_male'
      CHECK (avatar_base IN (
        'european_male','european_female',
        'dark_male','dark_female',
        'asian_male','asian_female',
        'android_male','android_female'
      )),
    active_title TEXT,
    active_badge_1 TEXT,
    active_badge_2 TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS chronos.catalog_items (
    item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    currency TEXT NOT NULL CHECK (currency IN ('CR','EX')),
    price BIGINT NOT NULL DEFAULT 0 CHECK (price >= 0),
    equip_slot TEXT NOT NULL CHECK (equip_slot IN ('eyes','neck','hand_prop','aura','frame')),
    rarity TEXT NOT NULL DEFAULT 'common'
      CHECK (rarity IN ('common','rare','epic','legendary')),
    visual_key TEXT NOT NULL,
    is_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    is_proposed BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS chronos.inventory (
    user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    item_id BIGINT NOT NULL REFERENCES chronos.catalog_items(item_id),
    acquired_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    acquisition_source TEXT NOT NULL DEFAULT 'store',
    PRIMARY KEY (user_id, item_id)
);

CREATE TABLE IF NOT EXISTS chronos.equipment (
    user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    equip_slot TEXT NOT NULL CHECK (equip_slot IN ('eyes','neck','hand_prop','aura','frame')),
    item_id BIGINT NOT NULL,
    equipped_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, equip_slot),
    CONSTRAINT chronos_equipment_owned_item
      FOREIGN KEY (user_id, item_id)
      REFERENCES chronos.inventory(user_id, item_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS chronos.ledger (
    ledger_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    currency TEXT NOT NULL CHECK (currency IN ('CR','EX','XP')),
    amount BIGINT NOT NULL CHECK (amount <> 0),
    reason_code TEXT NOT NULL,
    reference_key TEXT,
    idempotency_key TEXT NOT NULL UNIQUE,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_by BIGINT REFERENCES public.users(user_id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS chronos_ledger_user_currency_idx
  ON chronos.ledger(user_id, currency, created_at DESC);

CREATE TABLE IF NOT EXISTS chronos.achievement_definitions (
    achievement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    description TEXT NOT NULL,
    tier TEXT NOT NULL DEFAULT 'common'
      CHECK (tier IN ('common','rare','epic','legendary')),
    criteria JSONB NOT NULL DEFAULT '{}'::jsonb,
    reward_cr BIGINT NOT NULL DEFAULT 0 CHECK (reward_cr >= 0),
    reward_xp BIGINT NOT NULL DEFAULT 0 CHECK (reward_xp >= 0),
    is_enabled BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS chronos.user_achievements (
    user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    achievement_id BIGINT NOT NULL REFERENCES chronos.achievement_definitions(achievement_id),
    awarded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    source_key TEXT,
    PRIMARY KEY(user_id, achievement_id)
);

CREATE TABLE IF NOT EXISTS chronos.games (
    game_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_id BIGINT NOT NULL REFERENCES chronos.seasons(season_id) ON DELETE CASCADE,
    bot_event_id INTEGER NOT NULL REFERENCES public.events(event_id) ON DELETE RESTRICT,
    external_game_id TEXT NOT NULL,
    game_number SMALLINT,
    played_at TIMESTAMPTZ,
    status TEXT NOT NULL DEFAULT 'confirmed' CHECK (status IN ('draft','confirmed','void')),
    counts_for_sync BOOLEAN NOT NULL DEFAULT TRUE,
    source_import_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chronos_games_external_unique UNIQUE(season_id, external_game_id)
);
CREATE INDEX IF NOT EXISTS chronos_games_event_idx
  ON chronos.games(bot_event_id, status, played_at);

CREATE TABLE IF NOT EXISTS chronos.game_players (
    game_id BIGINT NOT NULL REFERENCES chronos.games(game_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE RESTRICT,
    placement SMALLINT CHECK (placement > 0),
    role_name TEXT,
    points NUMERIC(10,2) NOT NULL DEFAULT 0,
    bonus_points NUMERIC(10,2) NOT NULL DEFAULT 0,
    is_winner BOOLEAN NOT NULL DEFAULT FALSE,
    stats JSONB NOT NULL DEFAULT '{}'::jsonb,
    PRIMARY KEY(game_id, user_id)
);
CREATE INDEX IF NOT EXISTS chronos_game_players_user_idx
  ON chronos.game_players(user_id, game_id);

CREATE TABLE IF NOT EXISTS chronos.import_batches (
    import_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_id BIGINT NOT NULL REFERENCES chronos.seasons(season_id) ON DELETE CASCADE,
    import_type TEXT NOT NULL CHECK (import_type IN ('ranking','game_results')),
    bot_event_id INTEGER REFERENCES public.events(event_id) ON DELETE RESTRICT,
    file_name TEXT NOT NULL,
    content_type TEXT NOT NULL,
    source_image BYTEA NOT NULL,
    ocr_text TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'needs_review'
      CHECK (status IN ('needs_review','confirmed','rejected')),
    review_payload JSONB,
    uploaded_by BIGINT NOT NULL REFERENCES public.users(user_id),
    confirmed_by BIGINT REFERENCES public.users(user_id),
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    confirmed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS chronos_import_batches_status_idx
  ON chronos.import_batches(status, uploaded_at DESC);

CREATE TABLE IF NOT EXISTS chronos.ranking_snapshots (
    snapshot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_id BIGINT NOT NULL REFERENCES chronos.seasons(season_id) ON DELETE CASCADE,
    import_id BIGINT UNIQUE REFERENCES chronos.import_batches(import_id),
    captured_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    confirmed_by BIGINT NOT NULL REFERENCES public.users(user_id)
);
CREATE TABLE IF NOT EXISTS chronos.ranking_players (
    snapshot_id BIGINT NOT NULL REFERENCES chronos.ranking_snapshots(snapshot_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE RESTRICT,
    rank_position INTEGER NOT NULL CHECK(rank_position > 0),
    points NUMERIC(12,2) NOT NULL DEFAULT 0,
    games_played INTEGER NOT NULL DEFAULT 0 CHECK(games_played >= 0),
    wins INTEGER NOT NULL DEFAULT 0 CHECK(wins >= 0),
    bonus_points NUMERIC(12,2) NOT NULL DEFAULT 0,
    extra_stats JSONB NOT NULL DEFAULT '{}'::jsonb,
    PRIMARY KEY(snapshot_id, user_id),
    UNIQUE(snapshot_id, rank_position),
    CHECK(wins <= games_played)
);
CREATE INDEX IF NOT EXISTS chronos_ranking_players_user_idx
  ON chronos.ranking_players(user_id, snapshot_id DESC);

ALTER TABLE chronos.games
  ADD CONSTRAINT chronos_games_source_import_fk
  FOREIGN KEY(source_import_id) REFERENCES chronos.import_batches(import_id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS chronos.attendance (
    attendance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_id BIGINT NOT NULL REFERENCES chronos.seasons(season_id) ON DELETE CASCADE,
    slot_id BIGINT NOT NULL REFERENCES chronos.event_slots(slot_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    invited BOOLEAN NOT NULL DEFAULT FALSE,
    status TEXT NOT NULL DEFAULT 'pending'
      CHECK(status IN ('pending','attended','declined','no_response','no_show','not_invited')),
    marked_by BIGINT REFERENCES public.users(user_id),
    marked_at TIMESTAMPTZ,
    UNIQUE(slot_id, user_id)
);

CREATE TABLE IF NOT EXISTS chronos.final_invitations (
    invitation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_id BIGINT NOT NULL REFERENCES chronos.event_slots(slot_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    rank_at_invite INTEGER NOT NULL CHECK(rank_at_invite > 0),
    status TEXT NOT NULL DEFAULT 'pending'
      CHECK(status IN ('pending','accepted','declined','passed','no_response','no_show')),
    invited_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deadline_at TIMESTAMPTZ NOT NULL,
    responded_at TIMESTAMPTZ,
    UNIQUE(slot_id,user_id),
    UNIQUE(slot_id,rank_at_invite)
);

CREATE TABLE IF NOT EXISTS chronos.activity_events (
    activity_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_id BIGINT NOT NULL REFERENCES chronos.seasons(season_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    action_code TEXT NOT NULL,
    score_value NUMERIC(10,2) NOT NULL DEFAULT 0,
    source_key TEXT NOT NULL UNIQUE,
    verified BOOLEAN NOT NULL DEFAULT FALSE,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS chronos_activity_user_idx
  ON chronos.activity_events(season_id,user_id,created_at DESC);

CREATE TABLE IF NOT EXISTS chronos.minigame_sessions (
    session_id UUID PRIMARY KEY,
    season_id BIGINT NOT NULL REFERENCES chronos.seasons(season_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    game_code TEXT NOT NULL CHECK(game_code IN ('CODE_BREAKER','MEMORY')),
    status TEXT NOT NULL DEFAULT 'running'
      CHECK(status IN ('running','completed','failed','expired')),
    state JSONB NOT NULL,
    score INTEGER NOT NULL DEFAULT 0,
    actions_count INTEGER NOT NULL DEFAULT 0,
    xp_awarded INTEGER NOT NULL DEFAULT 0,
    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS chronos_minigame_daily_idx
  ON chronos.minigame_sessions(user_id,game_code,started_at DESC);

CREATE TABLE IF NOT EXISTS chronos.prediction_markets (
    market_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_id BIGINT NOT NULL REFERENCES chronos.seasons(season_id) ON DELETE CASCADE,
    bot_event_id INTEGER NOT NULL REFERENCES public.events(event_id) ON DELETE CASCADE,
    market_type TEXT NOT NULL CHECK(market_type IN ('TOP1','TOP2','TOP3')),
    status TEXT NOT NULL DEFAULT 'draft'
      CHECK(status IN ('draft','open','locked','settled','void')),
    opened_at TIMESTAMPTZ,
    closes_at TIMESTAMPTZ,
    settled_at TIMESTAMPTZ,
    winning_user_id BIGINT REFERENCES public.users(user_id),
    created_by BIGINT REFERENCES public.users(user_id),
    UNIQUE(bot_event_id,market_type)
);
CREATE TABLE IF NOT EXISTS chronos.prediction_candidates (
    market_id BIGINT NOT NULL REFERENCES chronos.prediction_markets(market_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    probability NUMERIC(10,8) NOT NULL CHECK(probability > 0 AND probability <= 1),
    odds NUMERIC(10,3) NOT NULL CHECK(odds >= 1),
    PRIMARY KEY(market_id,user_id)
);
CREATE TABLE IF NOT EXISTS chronos.prediction_bets (
    bet_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    market_id BIGINT NOT NULL REFERENCES chronos.prediction_markets(market_id) ON DELETE RESTRICT,
    bettor_user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE RESTRICT,
    candidate_user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE RESTRICT,
    stake BIGINT NOT NULL CHECK(stake > 0),
    odds NUMERIC(10,3) NOT NULL CHECK(odds >= 1),
    potential_return BIGINT NOT NULL CHECK(potential_return > 0),
    status TEXT NOT NULL DEFAULT 'pending'
      CHECK(status IN ('pending','won','lost','refunded')),
    placed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    settled_at TIMESTAMPTZ,
    UNIQUE(market_id,bettor_user_id)
);
CREATE INDEX IF NOT EXISTS chronos_prediction_bets_player_idx
  ON chronos.prediction_bets(bettor_user_id,placed_at DESC);

CREATE TABLE IF NOT EXISTS chronos.notifications (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    category TEXT NOT NULL
      CHECK(category IN ('finals','season','rewards','predictions','events','system')),
    title TEXT NOT NULL,
    body TEXT NOT NULL,
    action_type TEXT,
    action_payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    read_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS chronos_notifications_user_idx
  ON chronos.notifications(user_id,created_at DESC);

CREATE TABLE IF NOT EXISTS chronos.prize_rules (
    prize_rule_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_id BIGINT NOT NULL REFERENCES chronos.seasons(season_id) ON DELETE CASCADE,
    event_kind TEXT NOT NULL CHECK(event_kind IN ('intermediate_final','main_final','legacy')),
    place SMALLINT NOT NULL CHECK(place > 0),
    amount_uah BIGINT NOT NULL CHECK(amount_uah >= 0),
    is_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    rule_note TEXT NOT NULL DEFAULT '',
    UNIQUE(season_id,event_kind,place)
);
CREATE TABLE IF NOT EXISTS chronos.prize_awards (
    award_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_id BIGINT NOT NULL REFERENCES chronos.seasons(season_id) ON DELETE CASCADE,
    slot_id BIGINT REFERENCES chronos.event_slots(slot_id) ON DELETE SET NULL,
    event_kind TEXT NOT NULL CHECK(event_kind IN ('intermediate_final','main_final','legacy')),
    user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE RESTRICT,
    place SMALLINT NOT NULL CHECK(place > 0),
    base_amount_uah BIGINT NOT NULL CHECK(base_amount_uah >= 0),
    activity_coefficient NUMERIC(6,4) NOT NULL DEFAULT 1.0
      CHECK(activity_coefficient >= 0 AND activity_coefficient <= 1),
    final_amount_uah BIGINT NOT NULL CHECK(final_amount_uah >= 0),
    status TEXT NOT NULL DEFAULT 'draft'
      CHECK(status IN ('draft','approved','paid','void')),
    approved_by BIGINT REFERENCES public.users(user_id),
    approved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE(slot_id,event_kind,user_id)
);

CREATE TABLE IF NOT EXISTS chronos.audit_log (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT REFERENCES public.users(user_id) ON DELETE SET NULL,
    action_code TEXT NOT NULL,
    target_type TEXT NOT NULL,
    target_id TEXT,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS chronos_audit_created_idx
  ON chronos.audit_log(created_at DESC);

